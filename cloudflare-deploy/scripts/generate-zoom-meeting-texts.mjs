import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const sourcePath = new URL("../message_zoom.md", import.meta.url);
const outputPath = new URL("../zoom_meeting_texts.js", import.meta.url);
const outputFile = fileURLToPath(outputPath);
const MAX_MESSAGE_LENGTH = 950;

const MESSAGE_KEYS = Object.freeze([
  "minute_silence",
  "prayer",
  "preambula",
  "newcomer",
  "steps12",
  "traditions12",
  "meeting_rules",
  "chat_cleanliness",
  "seventh_tradition",
  "tea_rules",
  "speaker_questions",
  "scam_warning",
  "free_services",
  "group_sponsors",
  "telemost_link",
  "theme_monday",
  "theme_tuesday",
  "theme_thursday",
  "theme_friday",
  "theme_sunday",
  "meeting_schedule"
]);

const WEEKDAY_KEYS = Object.freeze({
  "0": "theme_sunday",
  "1": "theme_monday",
  "2": "theme_tuesday",
  "4": "theme_thursday",
  "5": "theme_friday"
});

function normalizeMarkdownKey(line) {
  return line.trim().replace(/\\([_.])/gu, "$1").replace(/:$/u, "");
}

function unescapeMarkdownPunctuation(text) {
  return text
    .replace(/\\([_.])/gu, "$1")
    .replace(/&#x20;/giu, " ");
}

function parseSource(source) {
  const messages = new Map();
  let activeKey = null;
  let activeLines = [];

  const saveActive = () => {
    if (activeKey === null) return;
    assert.ok(!messages.has(activeKey), `Duplicate Zoom message key: ${activeKey}`);
    const text = unescapeMarkdownPunctuation(activeLines.join("\n")).trim();
    assert.ok(text, `Zoom message ${activeKey} is empty`);
    messages.set(activeKey, text);
  };

  for (const line of source.replace(/\r\n?/gu, "\n").split("\n")) {
    const key = normalizeMarkdownKey(line);
    if (MESSAGE_KEYS.includes(key)) {
      saveActive();
      activeKey = key;
      activeLines = [];
    } else if (activeKey !== null) {
      if (line.trim().endsWith(":") && /^[a-z][a-z0-9_]*$/u.test(key)) throw new Error(`Unknown Zoom message key: ${key}`);
      activeLines.push(line);
    } else if (line.trim()) {
      throw new Error(`Unexpected content before the first Zoom message key: ${line}`);
    }
  }
  saveActive();

  assert.deepEqual([...messages.keys()], MESSAGE_KEYS, "The Markdown source must contain each required Zoom message exactly once and in canonical order");
  return Object.fromEntries([...messages].map(([key, text]) => [key, splitMessage(text)]));
}

function splitMessage(text, maxLength = MAX_MESSAGE_LENGTH) {
  const chunks = [];
  const visibleLength = (value) => Array.from(value.replace(/\*\*([^*\n]+)\*\*/gu, "$1")).length;
  let current = "";
  const flush = () => {
    const message = current.trim();
    if (message) chunks.push(message);
    current = "";
  };

  const splitLongLine = (line) => {
    const parts = [];
    const words = line.split(/(\s+)/u);
    let part = "";
    for (const word of words) {
      if (visibleLength(part + word) <= maxLength) {
        part += word;
        continue;
      }
      if (part.trim()) parts.push(part.trimEnd());
      part = word.trimStart();
      if (visibleLength(part) > maxLength) {
        const characters = Array.from(part);
        while (visibleLength(part) > maxLength) {
          const head = characters.splice(0, maxLength).join("");
          parts.push(head);
          part = characters.join("");
        }
      }
    }
    if (part.trim()) parts.push(part.trimEnd());
    return parts;
  };

  for (const line of text.trim().split("\n")) {
    if (visibleLength(line) > maxLength) {
      flush();
      for (const part of splitLongLine(line)) chunks.push(part);
      continue;
    }
    const candidate = current ? `${current}\n${line}` : line;
    if (visibleLength(candidate) <= maxLength) current = candidate;
    else {
      flush();
      current = line;
    }
  }
  flush();
  assert.ok(chunks.every((chunk) => visibleLength(chunk) <= maxLength), "Generated Zoom message exceeds the 950-character visible-text limit");
  return chunks;
}

function escapeNonAscii(text) {
  return Array.from(text, (character) => {
    const codePoint = character.codePointAt(0);
    if (codePoint <= 0x7f) return character;
    if (codePoint <= 0xffff) return `\\u${codePoint.toString(16).padStart(4, "0")}`;
    const value = codePoint - 0x10000;
    const high = 0xd800 + (value >> 10);
    const low = 0xdc00 + (value & 0x3ff);
    return `\\u${high.toString(16)}\\u${low.toString(16)}`;
  }).join("");
}

function renderModule(messages) {
  const json = escapeNonAscii(JSON.stringify(messages, null, 2));
  const weekdays = escapeNonAscii(JSON.stringify(WEEKDAY_KEYS, null, 2));
  return [
    "// Generated from message_zoom.md by scripts/generate-zoom-meeting-texts.mjs. Do not edit this file directly.",
    `export const ZOOM_MEETING_MESSAGE_TEXTS = ${json};`,
    "",
    `export const ZOOM_TOPIC_MESSAGE_KEYS_BY_WEEKDAY = ${weekdays};`,
    ""
  ].join("\n");
}

const source = await readFile(sourcePath, "utf8");
const generated = renderModule(parseSource(source));
if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8");
  assert.equal(existing, generated, "zoom_meeting_texts.js is stale; run npm run generate:zoom-texts");
  console.log("Zoom message source and generated Worker module are synchronized.");
} else {
  await writeFile(outputPath, generated, "utf8");
  console.log(`Generated ${outputFile}`);
}
